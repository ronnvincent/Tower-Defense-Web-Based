#!/usr/bin/env node
/**
 * write_asset_manifest.mjs — render `docs/asset-manifest.md` from the real files.
 *
 * The manifest in `src/data/assetManifest.js` is the source of truth; this
 * script only formats it. Before writing, every path it is about to promise is
 * opened and its PNG header is read, so the document can never claim a frame
 * grid the art does not have:
 *
 *   - enemy strips: height must be exactly `rows * frameHeight` (9 rows)
 *   - tower strips: both the base and the weapon file must exist
 *   - projectiles / impacts / fx strips: file must exist
 *
 * Exits non-zero on any mismatch, which is what makes it usable in CI.
 *
 *   node scripts/write_asset_manifest.mjs           # verify + write
 *   node scripts/write_asset_manifest.mjs --check    # verify only (no write)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  ASSET_PACKS,
  enemyAnimationReport,
  towerAnimationReport,
  effectTextureReport,
  animationGapSummary,
} from '../src/data/assetManifest.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CHECK_ONLY = process.argv.includes('--check');

/** Minimal PNG header reader — width/height live in the IHDR chunk. */
export function pngSize(file) {
  const fd = fs.openSync(file, 'r');
  try {
    const head = Buffer.alloc(33);
    fs.readSync(fd, head, 0, 33, 0);
    const signature = '89504e470d0a1a0a';
    if (head.subarray(0, 8).toString('hex') !== signature) return null;
    return { width: head.readUInt32BE(16), height: head.readUInt32BE(20) };
  } finally {
    fs.closeSync(fd);
  }
}

const problems = [];
function expectFile(relPath, { width = 0, height = 0 } = {}) {
  const abs = path.join(ROOT, relPath);
  if (!fs.existsSync(abs)) {
    problems.push(`missing file: ${relPath}`);
    return null;
  }
  const size = pngSize(abs);
  if (!size) return null; // not a PNG (svg source, etc.) — the existence check is enough
  if (width && size.width < width) problems.push(`${relPath}: width ${size.width} < frame ${width}`);
  if (height && size.height !== height) {
    problems.push(`${relPath}: height ${size.height} != expected ${height}`);
  }
  return size;
}

const enemies = enemyAnimationReport();
const towers = towerAnimationReport();
const effects = effectTextureReport();
const gap = animationGapSummary();

for (const entry of enemies) {
  expectFile(entry.file, { width: entry.frameWidth, height: entry.rows * entry.frameHeight });
}
for (const entry of towers) {
  // The base is one static image at no fixed size; the weapon is a horizontal
  // strip of exactly `frames` cells, which is what the animation cuts.
  expectFile(entry.base);
  const size = expectFile(entry.weapon);
  if (size) {
    if (size.height !== entry.frameHeight) {
      problems.push(`${entry.weapon}: height ${size.height} != frame ${entry.frameHeight}`);
    }
    if (size.width !== entry.frameWidth * entry.frames) {
      problems.push(`${entry.weapon}: width ${size.width} != ${entry.frames} x ${entry.frameWidth}`);
    }
  }
}
const seenEffectFiles = new Set();
for (const entry of [...effects.projectiles, ...effects.impacts, ...effects.strips]) {
  if (seenEffectFiles.has(entry.file)) continue;
  seenEffectFiles.add(entry.file);
  expectFile(entry.file);
}

if (problems.length) {
  console.error(`asset manifest check FAILED (${problems.length} problem(s))`);
  for (const problem of problems.slice(0, 40)) console.error(`  - ${problem}`);
  process.exit(1);
}

const table = (rows, head) => [
  `| ${head.join(' | ')} |`,
  `| ${head.map(() => '---').join(' | ')} |`,
  ...rows.map((row) => `| ${row.join(' | ')} |`),
].join('\n');

const stamp = new Date().toISOString().slice(0, 10);
