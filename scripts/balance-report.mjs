#!/usr/bin/env node
/**
 * Balance report.
 *
 * Prints the same numbers `tests/branch-niche.test.js` asserts on, as Markdown,
 * so the design of the shop can be read without running the tests and diffed
 * between commits. Regenerate with:
 *
 *     node scripts/balance-report.mjs > docs/balance.md
 *
 * Everything comes from `tests/helpers/balance.js`, which mirrors the runtime
 * (CombatCalculator armour maths, Projectile splash/chain, Enemy.applyDot), so
 * there is exactly one model of "how much damage does this do" in the project.
 */

import { TOWER_TYPES } from '../src/data/towerData.js';
import { ENEMY_TYPES } from '../src/data/enemyData.js';
import { NICHE, TARGETS, costAt, statsAt, throughput, utilityOf } from '../tests/helpers/balance.js';

const NICHES = {
  pack: 'Crowds',
  single: 'Single target',
  armor: 'Armour (40)',
  boss: 'Bosses',
  control: 'Control',
  support: 'Support',
};

const fmt = (n) => (n >= 1000 ? `${(n / 1000).toFixed(1)}k` : String(Math.round(n)));
const pad = (s, n) => String(s).padEnd(n);


const INTRO = `## Why this file exists

The shop sells twenty-one defence lines with two branches each, and for a long time
the second branch was often decoration. Measured against the same targets, one
branch beat its sibling on **every** column — sometimes while also being cheaper:

| Line | Branch that lost | What beat it |
| --- | --- | --- |
| archer | Rapid Ranger | Sniper: more damage on crowds, on armour *and* on bosses, plus 70 px more range |
| forge | Thunderforge | Emberforge: more damage on crowds, on plate and on titans |
| crossbow | Repeater | Siege Arbalest: more damage everywhere, including the crowd it advertises |
| gatling | Shredder | Storm Repeater: more damage even against 70 armour |
| flamer | Napalm Mortar | Inferno Siphon: more damage everywhere, for less gold |
| venom | Corrosive Still | Plague Vat: more damage everywhere, splash included |
| banner | Muster Camp | Warbanner: more damage and a stronger aura |

A player who read *"blistering fire rate — shreds swarms"* and bought the
swarm-clearer was buying the worse tower. The fix was not a numbers nudge: each
branch was given one job, and then the numbers were moved until the job was true.

What each branch is for now:

- **archer** — Rapid Ranger clears crowds (two and three bolts per draw), Sniper
  takes bosses and armour from further away.
- **cannon** — Siege Sling lobs a bigger blast into a pack; Stone Hammer breaks
  25–40 armour off whatever it lands on, and every other tower benefits.
- **frost** — Blizzard keeps the slow (60–75 %) and gains a nova at level 5;
  Lightning Conductor is the damage branch through chain lightning.
- **forge** — Emberforge is the blast (and no longer strips armour as well,
  which is what made it unbeatable); Thunderforge carries the penetration.
- **runes** — Void Lance is true damage plus armour break for titans; Arcane
  Nova is the splash.
- **banner** — Warbanner is the damage standard, Muster Camp is the economy
  standard (gold per kill, fire rate). They no longer compete on damage.
- **crossbow** — Repeater is the rate of fire (4.3 bolts/s); Siege Arbalest is
  the single shot with boss bonus and range.
- **gatling** — Storm wins the unarmoured column; Shredder trades shell for
  30–40 armour stripped per burst, which is what makes plate killable.
- **flamer** — Inferno is the concentrated burn, Napalm the wide pool.
- **venom** — Plague is the cloud (splash + poison), Corrosive one heavy dose
  that eats armour.
- **harpoon** — Ballista is the boss executioner, Grapple is crowd control
  (55 % slow, 1.2 s stun).

`;

const lines = [];
lines.push('# Balance model');
lines.push('');
lines.push('Generated by `node scripts/balance-report.mjs`. Do not edit by hand.');
lines.push('');
lines.push(INTRO);
lines.push('## How the numbers are produced');
lines.push('');
lines.push('Every figure below is effective damage per second against a concrete target,');
lines.push('computed with the same maths the game runs:');
lines.push('');
lines.push('| Mechanic | Source | Model |');
lines.push('| --- | --- | --- |');
lines.push('| Armour | `CombatCalculator.calculateDamage` | `100 / (100 + armour)` after armour break and penetration |');
lines.push('| Penetration | `DAMAGE_TYPE` | piercing +0.5, magic / lightning +0.75, true 1.0, on top of the tower\'s own `armorPenetration` |');
lines.push('| Armour break | `Enemy.applyDamage` | persists on the target for `armorBreakMs` and is refreshed, so sustained fire keeps it applied |');
lines.push('| Splash | `Projectile.hitEnemy` | 100 % at the centre, 40 % at the rim; extra bodies = `splash / 64 px`, averaged at 70 % |');
lines.push('| Chain | `Projectile.executeChainLightning` | 75 % damage per link |');
lines.push('| Burn / poison | `Enemy.applyDot` | one DoT per kind, refreshed — a tower that keeps firing sustains `damage / tickMs` |');
lines.push('| Boss bonus | `Projectile.hitEnemy` | `damage x (1 + bossBonus)` against `isBoss` targets |');
lines.push('');
lines.push('Targets: **crowds** = five unarmoured bodies inside the blast, **single** = one');
lines.push('unarmoured body, **armour** = the Brute (40), **bosses** = the Obsidian');
lines.push('Behemoth (armour 70, `isBoss`).');
lines.push('');
lines.push('## The niche matrix');
lines.push('');
lines.push('Each branch promises one job, and `tests/branch-niche.test.js` fails if the');
lines.push('numbers do not back the promise at levels 3, 4 and 5.');
lines.push('');
lines.push('| Line | Branch | Job | Level 3 | Level 4 | Level 5 |');
lines.push('| --- | --- | --- | --- | --- | --- |');
for (const [line, def] of Object.entries(TOWER_TYPES)) {
  for (const specKey of Object.keys(def.specializations || {})) {
    const niche = NICHE[line][specKey];
    const col = niche in TARGETS ? niche : null;
    const cells = [3, 4, 5].map((level) => {
      const stats = statsAt(line, specKey, level);
      if (!col) return utilityOf(stats).join(', ') || '—';
      return fmt(throughput(stats, TARGETS[col]));
    });
    lines.push(`| \`${line}\` | \`${specKey}\` | ${NICHES[niche]} | ${cells.join(' | ')} |`);
  }
}
lines.push('');
lines.push('Control and support branches show the utility they carry instead of a damage');
lines.push('column — a slow or an aura is the product, not the consolation prize.');
lines.push('');
lines.push('## Full table');
lines.push('');
lines.push('Cost is the **total gold** to reach that tier from an empty tile, so the two');
lines.push('branches of a line are directly comparable.');
lines.push('');
lines.push('| Line | Tier | Branch | Cost | Crowds | Single | Armour | Bosses | Single / gold |');
lines.push('| --- | :-: | --- | --: | --: | --: | --: | --: | --: |');
for (const [line, def] of Object.entries(TOWER_TYPES)) {
  const rows = [];
  for (const level of [1, 2]) {
    const stats = statsAt(line, '', level);
    rows.push({
      tier: `L${level}`,
      branch: '—',
      cost: costAt(line, Object.keys(def.specializations)[0], level),
      cols: Object.values(TARGETS).map((t) => throughput(stats, t)),
    });
  }
  for (const specKey of Object.keys(def.specializations)) {
    for (const level of [3, 4, 5]) {
      const stats = statsAt(line, specKey, level);
      rows.push({
        tier: `L${level}`,
        branch: specKey,
        cost: costAt(line, specKey, level),
        cols: Object.values(TARGETS).map((t) => throughput(stats, t)),
      });
    }
  }
  for (const row of rows) {
    const perGold = (row.cols[1] / row.cost).toFixed(3);
    lines.push(
      `| \`${line}\` | ${row.tier} | ${row.branch} | ${row.cost} | ${row.cols.map(fmt).join(' | ')} | ${perGold} |`
    );
  }
}
lines.push('');
lines.push('## Boss time-to-kill');
lines.push('');
lines.push('What the strongest single-target branch (`harpoon.ballista` at level 5,');
lines.push(`${fmt(throughput(statsAt('harpoon', 'ballista', 5), TARGETS.boss))} dps against a titan) needs to`);
lines.push('solo each boss. One maxed harpoon costs more than a whole wave pays out, so');
lines.push('these are floors rather than expectations.');
lines.push('');
lines.push('| Boss | HP | Armour | Sorted | One maxed harpoon | Four of them |');
lines.push('| --- | --: | --: | --: | --: | --: |');
const soloDps = throughput(statsAt('harpoon', 'ballista', 5), TARGETS.boss);
for (const [key, def] of Object.entries(ENEMY_TYPES)) {
  if (!def.isBoss) continue;
  const ttk = def.health / soloDps;
  lines.push(
    `| \`${key}\` | ${def.health} | ${def.armor} | ${def.shield ? `shield ${def.shield}` : '—'} | ${ttk.toFixed(1)} s | ${(ttk / 4).toFixed(1)} s |`
  );
}
lines.push('');
lines.push('## Regenerating');
lines.push('');
lines.push('```bash');
lines.push('node scripts/balance-report.mjs > docs/balance.md');
lines.push('npx vitest run tests/branch-niche.test.js');
lines.push('```');
lines.push('');

process.stdout.write(`${lines.join('\n')}`);
